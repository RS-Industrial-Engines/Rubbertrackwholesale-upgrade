/**
 * Get count of staged parts by brand
 */
export function getStagedPartCountByBrand(): Record<string, number> {
  const counts: Record<string, number> = {};
  for (const part of STAGED_PARTS) {
    counts[part.brand] = (counts[part.brand] || 0) + 1;
  }
  return counts;
}

/**
 * Alias: getStagedPartStats - returns brand counts and total
 * (matches documentation naming convention)
 */
export function getStagedPartStats(): { total: number; byBrand: Record<string, number> } {
  return {
    total: STAGED_PARTS.length,
    byBrand: getStagedPartCountByBrand(),
  };
}

/**
 * Get staged parts for a specific brand (internal enrichment only)
 * Alias: getStagedPartsByBrand wraps this for documentation consistency
 */
export function getStagedPartsForBrand(brand: string): StagedPart[] {
  return STAGED_PARTS.filter((p) => p.brand === brand);
}

/**
 * Alias: getStagedPartsByBrand - matches documentation naming convention
 */
export function getStagedPartsByBrand(brand: string): StagedPart[] {
  return getStagedPartsForBrand(brand);
}

/**
 * Look up staged alt part numbers for cross-reference enrichment
 * Returns staged parts whose primary or alt part numbers match the query
 */
export function findStagedPartByNumber(partNumber: string): StagedPart | undefined {
  const normalized = partNumber.toUpperCase().replace(/[^A-Z0-9]/g, "");
  return STAGED_PARTS.find((p) => {
    const primaryNorm = p.primary_part_number.toUpperCase().replace(/[^A-Z0-9]/g, "");
    if (primaryNorm === normalized) return true;
    return p.alt_part_numbers.some(
      (alt) => alt.toUpperCase().replace(/[^A-Z0-9]/g, "") === normalized
    );
  });
}

/**
 * Get staged parts with enriched data (those with compatible_models populated)
 * vs minimal data (extraction not completed)
 */
export function getStagedPartsByDataQuality(): {
  enriched: StagedPart[];
  minimal: StagedPart[];
} {
  const enriched: StagedPart[] = [];
  const minimal: StagedPart[] = [];
  
  for (const part of STAGED_PARTS) {
    if (part.compatible_models.length > 0 && part.compatible_models_text) {
      enriched.push(part);
    } else {
      minimal.push(part);
    }
  }
  
  return { enriched, minimal };
}

/**
 * Get staged parts that are ready for owner review
 * Ready = has compatible_models, has part_number, has brand
 * These are the highest-priority candidates for approval
 * (matches documentation naming convention: getStagedPartsReadyForReview)
 */
export function getStagedPartsReadyForReview(): StagedPart[] {
  return STAGED_PARTS.filter((p) => {
    return (
      p.brand &&
      p.primary_part_number &&
      p.compatible_models.length > 0 &&
      p.compatible_models_text.length > 0
    );
  });
}

/**
 * Normalize string for model matching (remove spaces, dashes, convert to uppercase)
 */
function normalizeForMatching(str: string): string {
  return str.toUpperCase().replace(/[\s\-_\.]/g, "");
}

/**
 * Map part_category to UndercarriageComponent type
 */
function mapPartCategoryToComponent(category: string, subtype: string): string {
  const categoryLower = category.toLowerCase();
  const subtypeLower = subtype?.toLowerCase() || "";
  
  if (categoryLower === "roller") {
    if (subtypeLower === "carrier" || subtypeLower === "top") {
      return "carrier-roller";
    }
    return "bottom-roller";
  }
  if (categoryLower === "sprocket" || categoryLower === "drive") {
    return "sprocket";
  }
  if (categoryLower === "idler") {
    return "idler";
  }
  if (categoryLower === "carrier-roller" || categoryLower === "top-roller") {
    return "carrier-roller";
  }
  return "bottom-roller"; // default
}

/**
 * Get staged parts for a specific brand+model+component combination
 * Used to display researched parts on machine component pages
 */
export function getStagedPartsForMachine(
  brand: string,
  model: string,
  componentType: string
): StagedPart[] {
  const normalizedBrand = brand.toUpperCase();
  const normalizedModel = normalizeForMatching(model);
  
  return STAGED_PARTS.filter((part) => {
    // Check brand (handle CAT/Caterpillar, etc.)
    const partBrandUpper = part.brand.toUpperCase();
    const brandMatches = 
      partBrandUpper === normalizedBrand ||
      (partBrandUpper === "CAT" && normalizedBrand === "CATERPILLAR") ||
      (partBrandUpper === "CATERPILLAR" && normalizedBrand === "CAT");
    
    if (!brandMatches) return false;
    
    // Check component type matches
    const partComponent = mapPartCategoryToComponent(part.part_category, part.part_subtype);
    if (partComponent !== componentType) return false;
    
    // Must have compatible models to display
    if (part.compatible_models.length === 0) return false;
    
    // Check if model matches any compatible model
    for (const compatModel of part.compatible_models) {
      const compatNormalized = normalizeForMatching(compatModel);
      if (compatNormalized === normalizedModel) return true;
      // Also check if the compatible model is contained in the search model or vice versa
      if (compatNormalized.includes(normalizedModel) || normalizedModel.includes(compatNormalized)) {
        return true;
      }
    }
    
    // Also check compatible_models_text for partial matches
    const textNormalized = normalizeForMatching(part.compatible_models_text);
    if (textNormalized.includes(normalizedModel)) return true;
    
    return false;
  });
}
