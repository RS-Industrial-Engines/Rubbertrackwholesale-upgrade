export const brands = Object.keys(machineModels).sort();

// Get all track sizes as a simple list
export const trackSizeList = trackSizes.map(t => t.size);

// Helper function to search machines by query
export function searchMachines(query: string): { make: string; model: string; trackSizes: string[] }[] {
  const normalizedQuery = query.toLowerCase().trim();
  const results: { make: string; model: string; trackSizes: string[] }[] = [];
  
  for (const [brand, models] of Object.entries(machineModels)) {
    for (const model of models) {
      const fullName = `${brand} ${model}`.toLowerCase();
      const modelLower = model.toLowerCase();
      
      if (fullName.includes(normalizedQuery) || modelLower.includes(normalizedQuery) || brand.toLowerCase().includes(normalizedQuery)) {
        const key = `${brand} ${model}`;
        const trackSizes = machineCompatibility[key] || [];
        results.push({
          make: brand,
          model: model,
          trackSizes
        });
      }
    }
  }
  
  return results.slice(0, 50); // Limit results
}

// Helper function to search track sizes by query  
export function searchTrackSizes(query: string): typeof trackSizes {
  const normalizedQuery = query.toLowerCase().replace(/\s+/g, '').replace(/x/gi, 'x');
  return trackSizes.filter(ts => 
    ts.size.toLowerCase().replace(/\s+/g, '').includes(normalizedQuery)
  );
}

// Helper function to determine if query is a track size
export function isTrackSizeQuery(query: string): boolean {
  // Track sizes follow patterns like: 400x86x52, 300x52.5x80
  const trackSizePattern = /^\d{3}x\d{2,3}\.?\d*x\d{2,3}$/i;
  const normalizedQuery = query.replace(/\s+/g, '');
  return trackSizePattern.test(normalizedQuery);
}

// Helper function to get machines by track size
export function getMachinesByTrackSize(trackSize: string): { make: string; model: string }[] {
  const normalizedSize = trackSize.toLowerCase().replace(/\s+/g, '');
  const results: { make: string; model: string }[] = [];
  
  for (const [machineKey, sizes] of Object.entries(machineCompatibility)) {
    const normalizedSizes = sizes.map(s => s.toLowerCase().replace(/\s+/g, ''));
    if (normalizedSizes.includes(normalizedSize)) {
      const parts = machineKey.split(' ');
      const make = parts[0];
      const model = parts.slice(1).join(' ');
      results.push({ make, model });
    }
  }
  
  return results;
}

// Get models by brand
export function getModelsByBrand(brand: string): string[] {
  return machineModels[brand] || [];
}
